#!/usr/bin/env bash
#
# backup.sh — резервное копирование каталога с ротацией старых архивов.
#
# Использование:
#   ./backup.sh -s /var/www -d /backup -k 7
#
#   -s  каталог-источник (обязательно)
#   -d  каталог для архивов (обязательно)
#   -k  сколько последних архивов хранить (по умолчанию 7)
#   -h  справка
#
# Коды возврата: 0 — успех, 1 — ошибка аргументов, 2 — ошибка выполнения.

set -euo pipefail          # -e: стоп при ошибке, -u: стоп при неопределённой переменной,
                           # -o pipefail: ошибка в любом звене пайпа роняет весь пайп

KEEP=7                     # значение по умолчанию для количества хранимых копий
SRC=""
DST=""
LOG_TAG="backup"           # тег, под которым записи уйдут в syslog

# --- логирование -------------------------------------------------------------
# Пишем и в stdout (видно при ручном запуске), и в syslog (видно при запуске из cron).
log() {
    local level="$1"; shift
    local msg="$*"
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] [$level] $msg"
    logger -t "$LOG_TAG" -p "user.${level,,}" "$msg" 2>/dev/null || true
}

die() {                    # фатальная ошибка: сообщение + выход с нужным кодом
    log "ERROR" "$1"
    exit "${2:-2}"
}

usage() {
    sed -n '3,12p' "$0" | sed 's/^# \{0,1\}//'   # печатаем шапку файла как справку
    exit 0
}

# --- разбор аргументов -------------------------------------------------------
while getopts "s:d:k:h" opt; do
    case "$opt" in
        s) SRC="$OPTARG" ;;
        d) DST="$OPTARG" ;;
        k) KEEP="$OPTARG" ;;
        h) usage ;;
        *) die "Неизвестный аргумент. Запустите с -h" 1 ;;
    esac
done

# --- валидация ---------------------------------------------------------------
[[ -n "$SRC" && -n "$DST" ]] || die "Не заданы -s и/или -d. Запустите с -h" 1
[[ -d "$SRC" ]]              || die "Каталог-источник не найден: $SRC" 1
[[ "$KEEP" =~ ^[0-9]+$ ]]    || die "-k должен быть числом, получено: $KEEP" 1
mkdir -p "$DST"              || die "Не удалось создать каталог назначения: $DST"

# Проверяем, что на диске есть место хотя бы с запасом в размер источника.
SRC_SIZE_KB=$(du -sk "$SRC" | awk '{print $1}')
FREE_KB=$(df -Pk "$DST" | awk 'NR==2 {print $4}')
if (( FREE_KB < SRC_SIZE_KB )); then
    die "Недостаточно места: нужно ~${SRC_SIZE_KB}K, свободно ${FREE_KB}K"
fi

# --- создание архива ---------------------------------------------------------
BASENAME=$(basename "$SRC")
STAMP=$(date '+%Y%m%d_%H%M%S')
ARCHIVE="${DST}/${BASENAME}_${STAMP}.tar.gz"

log "INFO" "Старт бэкапа: $SRC -> $ARCHIVE"

# -C переходит в родительский каталог, чтобы в архиве не было полного пути от /
if tar -czf "$ARCHIVE" -C "$(dirname "$SRC")" "$BASENAME" 2>/dev/null; then
    SIZE=$(du -h "$ARCHIVE" | awk '{print $1}')
    log "INFO" "Архив создан успешно, размер: $SIZE"
else
    rm -f "$ARCHIVE"       # битый архив хуже, чем отсутствие архива
    die "Ошибка при создании архива, незавершённый файл удалён"
fi

# Проверяем целостность: если архив не читается, толку от него нет.
if ! tar -tzf "$ARCHIVE" >/dev/null 2>&1; then
    rm -f "$ARCHIVE"
    die "Архив повреждён, файл удалён"
fi

# --- ротация -----------------------------------------------------------------
# Сортируем архивы этого источника по имени (в имени дата, поэтому сортировка = хронология),
# оставляем последние $KEEP, остальные удаляем.
mapfile -t ARCHIVES < <(find "$DST" -maxdepth 1 -name "${BASENAME}_*.tar.gz" -type f | sort)
TOTAL=${#ARCHIVES[@]}

if (( TOTAL > KEEP )); then
    REMOVE=$(( TOTAL - KEEP ))
    log "INFO" "Найдено $TOTAL архивов, храним $KEEP, удаляем $REMOVE"
    for (( i=0; i<REMOVE; i++ )); do
        rm -f "${ARCHIVES[$i]}"
        log "INFO" "Удалён старый архив: $(basename "${ARCHIVES[$i]}")"
    done
else
    log "INFO" "Всего архивов: $TOTAL, ротация не требуется"
fi

log "INFO" "Бэкап завершён"
exit 0
